-- Temporarily disable all constraints on the Products table.

DROP TABLE Products;

CREATE TABLE Products (
                          id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
                          name VARCHAR2(100),
                          price NUMBER,
                          category_id NUMBER,

                          CONSTRAINT PK_PRODUCTS PRIMARY KEY (id),
                          CONSTRAINT UQ_PRODUCTS_NAME UNIQUE (name),
                          CONSTRAINT CH_PRICE CHECK (price > 0),
                          CONSTRAINT NN_PRODUCT_NAME CHECK (name IS NOT NULL)
);

-- Show all CONSTRAINTS in the table

SELECT constraint_name, constraint_type
FROM all_constraints
WHERE owner = 'ITEM'
  AND table_name = 'PRODUCTS';


-- Generate commands to disable all CONSTRAINTS
