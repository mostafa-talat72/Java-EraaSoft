-- How would you disable all constraints on a table before bulk inserting data?

-- Show all constraints on the Products table.
SELECT constraint_name, constraint_type
FROM all_constraints
WHERE owner = 'ITEM'
  AND table_name = 'PRODUCTS';

-- Generate SQL statements to disable all constraints.
SELECT
    'ALTER TABLE ITEM.PRODUCTS DISABLE CONSTRAINT '
        || constraint_name || ';' AS disable_sql
FROM all_constraints
WHERE owner = 'ITEM'
  AND table_name = 'PRODUCTS';

-- Execute the generated ALTER TABLE statements before performing the bulk insert.
ALTER TABLE ITEM.PRODUCTS DISABLE CONSTRAINT CH_PRICE;
ALTER TABLE ITEM.PRODUCTS DISABLE CONSTRAINT NN_PRODUCT_NAME;
ALTER TABLE ITEM.PRODUCTS DISABLE CONSTRAINT PK_PRODUCTS;
ALTER TABLE ITEM.PRODUCTS DISABLE CONSTRAINT UQ_PRODUCTS_NAME;

-- Note:
-- Another approach is to use a PL/SQL block with EXECUTE IMMEDIATE.
-- This method generates and executes the ALTER TABLE statements automatically,
-- so there is no need to copy and run the generated SQL manually.

BEGIN
FOR c IN (
        SELECT constraint_name
        FROM all_constraints
        WHERE owner = 'ITEM'
          AND table_name = 'PRODUCTS'
          AND constraint_name NOT LIKE 'SYS_%'
    ) LOOP
        EXECUTE IMMEDIATE
            'ALTER TABLE ITEM.PRODUCTS DISABLE CONSTRAINT ' || c.constraint_name;
END LOOP;
END;




