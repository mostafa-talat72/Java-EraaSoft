------------------------------------------------------------
-- إنشاء مستخدم جديد باسم mostafa وتحديد كلمة المرور
------------------------------------------------------------
CREATE USER mostafa IDENTIFIED BY 123;

------------------------------------------------------------
-- منح المستخدم صلاحية تسجيل الدخول إلى قاعدة البيانات
------------------------------------------------------------
GRANT CREATE SESSION TO mostafa;

------------------------------------------------------------
-- منح المستخدم صلاحية إنشاء الجداول داخل الـ Schema الخاص به
------------------------------------------------------------
GRANT CREATE TABLE TO mostafa;

------------------------------------------------------------
-- منح المستخدم مساحة غير محدودة على الـ Tablespace USERS
-- حتى يتمكن من إنشاء الجداول وتخزين البيانات
------------------------------------------------------------
ALTER USER mostafa QUOTA UNLIMITED ON USERS;

------------------------------------------------------------
-- تسجيل الدخول بحساب mostafa
-- (يتم من SQL*Plus أو DBeaver)
-- CONNECT mostafa/123
------------------------------------------------------------

------------------------------------------------------------
-- إنشاء جدول Student يحتوي على:
-- id : المفتاح الأساسي
-- name : اسم الطالب
------------------------------------------------------------
CREATE TABLE Student
(
    id NUMBER PRIMARY KEY,
    name VARCHAR2(100)
);

------------------------------------------------------------
-- إضافة سجل جديد داخل الجدول
------------------------------------------------------------
INSERT INTO Student
VALUES (1,'Ahmed');

------------------------------------------------------------
-- عرض جميع البيانات الموجودة داخل الجدول
------------------------------------------------------------
SELECT *
FROM Student;

------------------------------------------------------------
-- تعديل اسم الطالب الذي رقمه 1
------------------------------------------------------------
UPDATE Student
SET name='Ali'
WHERE id=1;

------------------------------------------------------------
-- حذف الطالب الذي رقمه 1
------------------------------------------------------------
DELETE FROM Student
WHERE id=1;

------------------------------------------------------------
-- منح مستخدم HR صلاحيات:
-- القراءة والإضافة والتعديل والحذف
-- على جدول Student
------------------------------------------------------------
GRANT SELECT, INSERT, UPDATE, DELETE
    ON Student
    TO HR;

------------------------------------------------------------
-- تسجيل الدخول بحساب HR
-- CONNECT hr/hr
------------------------------------------------------------

------------------------------------------------------------
-- إضافة سجل جديد في جدول Student الخاص بالمستخدم mostafa
------------------------------------------------------------
INSERT INTO mostafa.Student
VALUES (3,'Hamoda');

------------------------------------------------------------
-- عرض بيانات جدول Student الخاص بالمستخدم mostafa
------------------------------------------------------------
SELECT *
FROM mostafa.Student;

------------------------------------------------------------
-- تعديل بيانات الطالب الذي رقمه 3
------------------------------------------------------------
UPDATE mostafa.Student
SET name='maro'
WHERE id=3;

------------------------------------------------------------
-- حذف الطالب الذي رقمه 3
------------------------------------------------------------
DELETE FROM mostafa.Student
WHERE id=3;

------------------------------------------------------------
-- العودة إلى حساب mostafa
-- سحب جميع الصلاحيات التي تم منحها للمستخدم HR
------------------------------------------------------------
REVOKE SELECT, INSERT, UPDATE, DELETE
    ON Student
    FROM HR;