package com.restauranttablereservationapi.mapper;

import com.restauranttablereservationapi.dto.ReservationStatusDTO;
import com.restauranttablereservationapi.dto.ReservationStatusRequestDTO;
import com.restauranttablereservationapi.model.ReservationStatus;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;
import org.mapstruct.MappingTarget;

import java.util.List;

@Mapper(componentModel = "spring")
public interface ReservationStatusMapper {

    ReservationStatusDTO convertFromStatusToStatusDto(ReservationStatus status);

    List<ReservationStatusDTO> convertFromStatusListToStatusDtoList(List<ReservationStatus> statuses);

    // The id is generated by the database, never sent by the client.
    @Mapping(target = "id", ignore = true)
    ReservationStatus convertFromStatusRequestDtoToStatus(ReservationStatusRequestDTO requestDTO);

    @Mapping(target = "id", ignore = true)
    void updateStatusFromStatusRequestDto(ReservationStatusRequestDTO requestDTO,
                                          @MappingTarget ReservationStatus status);
}
