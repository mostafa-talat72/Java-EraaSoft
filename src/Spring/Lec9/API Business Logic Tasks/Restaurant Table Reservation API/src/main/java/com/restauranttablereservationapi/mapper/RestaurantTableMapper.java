package com.restauranttablereservationapi.mapper;

import com.restauranttablereservationapi.dto.RestaurantTableDTO;
import com.restauranttablereservationapi.dto.RestaurantTableRequestDTO;
import com.restauranttablereservationapi.model.RestaurantTable;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;
import org.mapstruct.MappingTarget;

import java.util.List;

@Mapper(componentModel = "spring")
public interface RestaurantTableMapper {

    RestaurantTableDTO convertFromTableToTableDto(RestaurantTable table);

    List<RestaurantTableDTO> convertFromTableListToTableDtoList(List<RestaurantTable> tables);

    // The id is generated by the database, never sent by the client.
    @Mapping(target = "id", ignore = true)
    RestaurantTable convertFromTableRequestDtoToTable(RestaurantTableRequestDTO requestDTO);

    @Mapping(target = "id", ignore = true)
    void updateTableFromTableRequestDto(RestaurantTableRequestDTO requestDTO,
                                        @MappingTarget RestaurantTable table);
}
