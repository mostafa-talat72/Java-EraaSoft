package com.restauranttablereservationapi.mapper;

import com.restauranttablereservationapi.dto.CustomerDTO;
import com.restauranttablereservationapi.dto.CustomerRequestDTO;
import com.restauranttablereservationapi.model.Customer;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;
import org.mapstruct.MappingTarget;

import java.util.List;

@Mapper(componentModel = "spring")
public interface CustomerMapper {

    CustomerDTO convertFromCustomerToCustomerDto(Customer customer);

    List<CustomerDTO> convertFromCustomerListToCustomerDtoList(List<Customer> customers);

    // The id is generated by the database, never sent by the client.
    @Mapping(target = "id", ignore = true)
    Customer convertFromCustomerRequestDtoToCustomer(CustomerRequestDTO requestDTO);

    @Mapping(target = "id", ignore = true)
    void updateCustomerFromCustomerRequestDto(CustomerRequestDTO requestDTO,
                                              @MappingTarget Customer customer);
}
